// Generate the seller's ECDSA P-256 keypair once.
//
//   node scripts/generate-keys.mjs
//
// Writes:
//   scripts/keys/private.jwk.json   <- SECRET. Never commit. Never ship.
//   src/lib/licensePublicKey.ts     <- PUBLIC. Committed and shipped in the app.
//
// Run this once, keep private.jwk.json safe, then rebuild/redeploy the app.
// Re-running rotates the key and invalidates every key already sold.

import { generateKeyPairSync } from 'node:crypto'
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const keysDir = resolve(here, 'keys')
const privatePath = resolve(keysDir, 'private.jwk.json')
const publicModulePath = resolve(root, 'src/lib/licensePublicKey.ts')

const force = process.argv.includes('--force')

if (existsSync(privatePath) && !force) {
  const existing = JSON.parse(readFileSync(privatePath, 'utf8'))
  console.log('A keypair already exists at scripts/keys/private.jwk.json')
  console.log('Public key in use:')
  console.log(JSON.stringify({ kty: existing.kty, crv: existing.crv, x: existing.x, y: existing.y }, null, 2))
  console.log('\nRe-run with --force to rotate (this invalidates all previously issued keys).')
  process.exit(0)
}

const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' })
const priv = privateKey.export({ format: 'jwk' })
const pub = publicKey.export({ format: 'jwk' })

mkdirSync(keysDir, { recursive: true })
writeFileSync(privatePath, JSON.stringify(priv, null, 2) + '\n', { mode: 0o600 })

const publicJwk = { kty: pub.kty, crv: pub.crv, x: pub.x, y: pub.y }
const module = `// AUTO-GENERATED by scripts/generate-keys.mjs. Do not edit by hand.
// This is only a PUBLIC key: it can verify licenses but cannot create them.
// Regenerate with: node scripts/generate-keys.mjs --force

export const LICENSE_PUBLIC_KEY_JWK = ${JSON.stringify(publicJwk, null, 2)} as JsonWebKey
`
writeFileSync(publicModulePath, module)

console.log('Keypair written.')
console.log('  secret : scripts/keys/private.jwk.json  (keep this private!)')
console.log('  public : src/lib/licensePublicKey.ts    (safe to commit)')
console.log('\nNext: node scripts/issue-license.mjs --plan monthly --email buyer@example.com')
